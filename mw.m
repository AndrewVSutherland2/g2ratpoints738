// mw.m -- the statements of the note about the Mordell-Weil group of the Jacobian J of C_738, from the curve, its 369 known
// x-values (data/points_738.txt), a basis of the group they generate (data/mw_basis.txt) and coordinates in that basis
// (data/mw_coords.txt).      magma -b mw.m      (a few minutes)
//
//  1. The sextic f has Galois group S6, and J(Q) is torsion-free.
//  2. rank J(Q) >= 21.  Take P0 = (0, 2615), the 20 points with the x-values listed below and the point iota(P0).  The images
//     of their 21 classes [P - P0] in the sum of the groups J(F_l)/3J(F_l) over the 18 primes l <= 257 of good reduction with
//     3 | #J(F_l) span a space of dimension 21 over F_3.  As J(Q)[3] = 0, the classes are independent in J(Q).
//  3. The same question modulo 2.  The images of the 21 classes in the sum of the groups J(F_l)/2J(F_l) span dimension 20
//     only: the class b = [iota(P0) - P0] is divisible by 2 in every J(F_l), and the other 20 are independent.  But b is not
//     divisible by 2 in J(Q).  Indeed b = 2[iota(P0)] - K with K the canonical class, so a half of b would give a class
//     theta of degree 1 over Q with 2 theta = K.  The 16 such classes over Qbar are the six Weierstrass points and the ten
//     classes W_i + W_j + W_k - K, one for each splitting of the six roots of f into two triples, and S6 fixes none of them.
//     (This is the extra element in the kernel of the (x - T) map of 2-descent for a sextic: Stoll, Implementing 2-descent
//     for Jacobians of hyperelliptic curves, Lemma 5.1.)  So the 21 classes are independent modulo 2J(Q) as well.
//  4. Let Lambda be the subgroup of J(Q) generated by the classes [P - P0] of all known points P.  Every one of these classes
//     is the integer combination of b_1, ..., b_21 given in mw_coords.txt (checked exactly in J(Q)), and the coordinate
//     vectors span Z^21, so b_1, ..., b_21 lie in Lambda and generate it.  With 2, Lambda is free of rank 21 with this basis.
//  5. Lambda is saturated in J(Q) at p = 3, 5, 7, 11, 13: the reduction maps Lambda/p -> sum of J(F_q)/pJ(F_q) are
//     injective.  At p = 2 the kernel of the reduction is spanned by the class of b, which is not in 2J(Q) by 3, so
//     Lambda/2 -> J(Q)/2J(Q) is injective and Lambda is saturated at 2 as well.
//  6. The regulator of Lambda (canonical height pairing, numerical): about 5.7 x 10^12.
// The upper bound rank J(Q) <= 21 is not proved here; it comes from selmer.m and assumes GRH.
SetColumns(0); SetQuitOnError(true);
Q := Rationals(); R<x> := PolynomialRing(Q);
f := R![6838225, -46160230, 40133975, 172162750, 60026500, -16144220, 743425];
C := HyperellipticCurve(f); J := Jacobian(C);
disc := Integers()!Discriminant(f);
tt := Cputime();

// ---- 1. Galois group and torsion
degs := func< p | Sort([Degree(g[1]) : g in Factorization(PolynomialRing(GF(p))!f)]) >;
assert degs(67) eq [6] and degs(47) eq [1, 5] and degs(59) eq [1, 2, 3];
print "1. f is irreducible mod 67 and has factors of degrees 1,5 mod 47 and 1,2,3 mod 59: the Galois group is S6";
n43 := #Jacobian(ChangeRing(C, GF(43))); n47 := #Jacobian(ChangeRing(C, GF(47)));
assert disc mod 43 ne 0 and disc mod 47 ne 0 and n43 eq 3022 and n47 eq 3537 and GCD(n43, n47) eq 1;
printf "   #J(F_43) = %o and #J(F_47) = %o are coprime: J(Q) is torsion-free\n", n43, n47;

// ---- the points and the classes
pts := [];
for ln in Split(Read("data/points_738.txt"), "\n") do
  w := [StringToInteger(t) : t in Split(ln, " ")];
  if #w eq 3 then Append(~pts, C!w); end if;
end for;
assert #pts eq 369 and #{P[1]/P[3] : P in pts} eq 369 and pts[1] eq C![0, 2615, 1];
P0 := pts[1]; iP0 := C![0, -2615, 1];
xs := [-1/2, 1/2, -3/2, 1/3, 4/3, -3/4, 1/4, 5/2, -5/3, -2/5, -1/5, -6, -7/3, -7/5, 4/7, 8, 1/8, -11/6, 9/11, 12/5];
sel := [[P : P in pts | P[1]/P[3] eq t][1] : t in xs] cat [iP0];
D := [P - P0 : P in sel];
assert #D eq 21;

// images of a list of classes, given as differences of points, in the sum of J(F_l)/p over good primes l; stops when the
// rank reaches target
function Images(pairs, p, target, lmax : Tm := 0)
  M := ZeroMatrix(GF(p), #pairs, 0); l := 2; used := [];
  rk := func< M | Tm cmpeq 0 select Rank(M) else Rank(ChangeRing(Tm, GF(p)) * M) >;
  while l lt lmax and rk(M) lt target do
    l := NextPrime(l);
    if disc mod l eq 0 then continue; end if;
    Cl := ChangeRing(C, GF(l)); Jl := Jacobian(Cl);
    if #Jl mod p ne 0 then continue; end if;
    A, m := AbelianGroup(Jl);
    Qt, q := quo< A | [p*g : g in Generators(A)] >;
    red := func< P | Cl![GF(l) | P[1], P[2], P[3]] >;
    blk := Matrix(GF(p), #pairs, #Invariants(Qt), [Eltseq(q((red(pr[1]) - red(pr[2])) @@ m)) : pr in pairs]);
    M := HorizontalJoin(M, blk); Append(~used, l);
  end while;
  return M, used;
end function;

// ---- 2. rank >= 21 modulo 3
M3, used := Images([<P, P0> : P in sel], 3, 21, 1000);
assert Rank(M3) eq 21 and #used eq 18 and used[#used] eq 257;
printf "2. the 21 classes have independent images modulo 3 at the %o primes %o: rank J(Q) >= 21\n", #used, used;

// ---- 3. modulo 2
M2, used := Images([<P, P0> : P in sel], 2, 21, 400);
K := Kernel(M2);
assert Rank(M2) eq 20 and Dimension(K) eq 1 and Basis(K)[1] eq Vector(GF(2), [0 : i in [1..20]] cat [1]);
printf "3. modulo 2 at the %o good primes below 400 with #J(F_l) even: rank 20; the kernel is spanned by b = [iota(P0) - P0], which is not in 2J(Q)\n", #used;

// ---- 4. the basis and the coordinates
bas := [];
for ln in Split(Read("data/mw_basis.txt"), "\n") do
  if #ln eq 0 or ln[1] eq "#" then continue; end if;
  s := Split(ln, "|"); assert #s eq 3;
  Append(~bas, elt< J | R!eval(s[1]), R!eval(s[2]), StringToInteger(s[3]) >);
end for;
assert #bas eq 21;
rows := []; cpts := [];
for ln in Split(Read("data/mw_coords.txt"), "\n") do
  if #ln eq 0 or ln[1] eq "#" then continue; end if;
  w := [StringToInteger(t) : t in Split(ln, " ")]; assert #w eq 24;
  Append(~cpts, C!w[1..3]); Append(~rows, w[4..24]);
end for;
assert #rows eq 369 and cpts[1] eq iP0 and cpts[2..369] eq pts[2..369];
for i in [1..369] do
  assert cpts[i] - P0 eq &+[J | rows[i][j]*bas[j] : j in [1..21]];
end for;
H := HermiteForm(Matrix(Integers(), rows));
assert Submatrix(H, 1, 1, 21, 21) eq IdentityMatrix(Integers(), 21) and forall{i : i in [22..369] | IsZero(H[i])};
print "4. all 369 classes [P - P0] are the stated combinations of b_1, ..., b_21, and their coordinate vectors span Z^21: Lambda is free of rank 21 with this basis";
// the 21 classes of step 2 in this basis: they generate a subgroup of finite index
idx := [Index(cpts, P) : P in sel]; assert 0 notin idx;
printf "   the 21 classes of step 2 generate a subgroup of index %o in Lambda\n", Abs(Determinant(Matrix(Integers(), [rows[i] : i in idx])));

// ---- 5. saturation
// b_j as a combination of differences [P - P0]: T with T * rows = (identity; 0)
_, T := HermiteForm(Matrix(Integers(), rows));
supp := [i : i in [1..369] | exists{k : k in [1..21] | T[k][i] ne 0}];
for p in [2, 3, 5, 7, 11, 13] do
  target := p eq 2 select 20 else 21;
  // images of the differences in supp, then of the basis by linear algebra
  Ts := Matrix(Integers(), 21, #supp, [[T[k][i] : i in supp] : k in [1..21]]);
  Mp, used := Images([<cpts[i], P0> : i in supp], p, 21, p eq 2 select 400 else 3000 : Tm := Ts);
  B := ChangeRing(Ts, GF(p)) * Mp;
  if p eq 2 then
    K := Kernel(B);
    assert Rank(B) eq 20 and Basis(K)[1] eq Vector(GF(2), rows[1]);
    printf "5. p = 2: Lambda/2 has rank 20 in the reductions at %o primes; the kernel is the class of b, not in 2J(Q): saturated at 2\n", #used;
  else
    assert Rank(B) eq 21;
    printf "   p = %o: Lambda/%o injects into the reductions (%o primes up to %o): saturated at %o\n", p, p, #used, used[#used], p;
  end if;
end for;

// ---- 6. the regulator
G := HeightPairingMatrix(bas : Precision := 30);
reg := Determinant(G);
assert reg gt 5.6e12 and reg lt 5.8e12;
printf "6. regulator of Lambda: %o\n", RealField(6)!reg;
printf "MORDELL-WEIL CHECKS PASSED (%o s)\n", Cputime(tt);
quit;
